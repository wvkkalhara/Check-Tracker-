/* Check Tracker app shell. Firebase, authentication and financial API traffic are never cached. */
'use strict';

const CACHE_NAME = 'check-tracker-shell-v3';
const ROOT = new URL('./', self.location.href);
const SHELL = [
  ROOT.href,
  new URL('index.html', ROOT).href,
  new URL('manifest.webmanifest', ROOT).href,
  new URL('favicon.svg', ROOT).href
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(SHELL))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.map((key) => key === CACHE_NAME ? null : caches.delete(key))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  const url = new URL(request.url);

  if (request.method !== 'GET' || url.origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(new URL('index.html', ROOT).href, copy));
          }
          return response;
        })
        .catch(() => caches.match(new URL('index.html', ROOT).href))
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((cached) => cached || fetch(request).then((response) => {
      if (response.ok) {
        const copy = response.clone();
        caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
      }
      return response;
    }))
  );
});